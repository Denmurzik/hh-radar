"""Форматирование чисел и слов для человека.

Отдельный модуль, потому что этим пользуются и витрина, и командная строка,
а держать склонение числительных внутри отрисовки HTML — значит однажды
скопировать его во второе место.
"""

from __future__ import annotations

#: Неразрывный пробел для разделения разрядов. Записан кодом, а не символом:
#: невидимая U+00A0 в исходнике — источник тихих расхождений в тестах.
#: Смысл в том, чтобы «150 000 ₽» не переносилось посреди числа.
NBSP = "\u00a0"


def plural_ru(count: int, one: str, few: str, many: str) -> str:
    """Русское склонение числительных.

    «4 вакансий» в шапке витрины читается как небрежность, а витрина —
    первое, что видит человек по ссылке.

    >>> plural_ru(1, "вакансия", "вакансии", "вакансий")
    'вакансия'
    >>> plural_ru(11, "вакансия", "вакансии", "вакансий")
    'вакансий'
    >>> plural_ru(21, "вакансия", "вакансии", "вакансий")
    'вакансия'
    """
    # Числа от 11 до 14 — исключение: несмотря на последнюю цифру,
    # они всегда требуют форму родительного множественного.
    if count % 100 in range(11, 15):
        return many
    last = count % 10
    if last == 1:
        return one
    if last in (2, 3, 4):
        return few
    return many


def format_money(amount: int | None) -> str:
    """Сумма в рублях с неразрывными пробелами в разрядах.

    ``None`` остаётся прочерком: ноль в этом месте соврал бы, будто
    зарплата известна и равна нулю.
    """
    if amount is None:
        return "—"
    return f"{amount:,}".replace(",", " ") + " ₽"


def format_count(value: int) -> str:
    """Число с разделением разрядов."""
    return f"{value:,}".replace(",", " ")
